#!/usr/bin/env python3
"""Render the existing game catalogue as a GitHub-readable page, without network I/O."""

import argparse
import html
import json
import pathlib
import unicodedata
from datetime import date, datetime, timezone
from urllib.parse import quote, urlsplit


ROOT = pathlib.Path(__file__).resolve().parents[1]


def cell(value: str) -> str:
    """Keep catalogue text inside its Markdown table cell."""
    text = html.escape(str(value), quote=False)
    for character in "\\`*_[]":
        text = text.replace(character, "\\" + character)
    return text.replace("|", "&#124;").replace("\r", " ").replace("\n", " ")


def safe_url(value: str) -> str:
    try:
        parsed = urlsplit(value or "")
    except ValueError:
        return ""
    if parsed.scheme != "https" or not parsed.netloc:
        return ""
    return quote(value, safe=":/?#=&%+@,;~!$'*-._")


def pcgw_url(game: dict) -> str:
    return safe_url(game.get("manualFixUrl", "")) or (
        "https://www.pcgamingwiki.com/wiki/" + quote(game["title"].replace(" ", "_"), safe="")
    )


def manual_feature(game: dict, feature: str) -> bool:
    # Older catalogues may only have the game-wide flag. Be conservative then.
    has_feature_flags = any(key in game for key in ("adaptiveTriggersManualFix", "hapticFeedbackManualFix"))
    return bool(game.get(feature + "ManualFix")) or (
        not has_feature_flags and bool(game.get("requiresManualFix"))
    )


def feature_status(game: dict, feature: str) -> str:
    if not game.get(feature):
        return "—"
    return "🛠️ Manual fix" if manual_feature(game, feature) else "✅ Native"


def needs_manual_fix(game: dict) -> bool:
    return bool(game.get("requiresManualFix")) or any(
        game.get(feature) and manual_feature(game, feature)
        for feature in ("adaptiveTriggers", "hapticFeedback")
    )


def manual_links(game: dict) -> str:
    if not needs_manual_fix(game):
        return "—"
    links = [f"[PCGamingWiki]({pcgw_url(game)})"]
    seen = {pcgw_url(game)}
    for feature in ("adaptiveTriggers", "hapticFeedback"):
        for link in game.get("manualFixDetails", {}).get(feature, {}).get("links", []):
            url = safe_url(link.get("url", ""))
            if url and url not in seen:
                links.append(f"[{cell(link.get('label') or 'Fix')}]({url})")
                seen.add(url)
    return " · ".join(links)


def added_date(game: dict) -> str:
    try:
        return date.fromisoformat(game.get("addedAt", "")).isoformat()
    except (ValueError, TypeError):
        return ""


def initial(game: dict) -> str:
    first = unicodedata.normalize("NFKD", game["title"]).upper()[:1]
    if first in "0123456789":
        return "0-9"
    return first if first and "A" <= first <= "Z" else "Other"


def render_catalogue(data: dict) -> str:
    games = sorted(data["games"], key=lambda game: game["title"].casefold())
    updated = "Not recorded"
    if data.get("updatedAt"):
        stamp = datetime.fromisoformat(data["updatedAt"].replace("Z", "+00:00"))
        updated = stamp.replace(tzinfo=stamp.tzinfo or timezone.utc).astimezone(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    adaptive = sum(bool(game.get("adaptiveTriggers")) for game in games)
    haptic = sum(bool(game.get("hapticFeedback")) for game in games)
    manual = sum(needs_manual_fix(game) for game in games)
    lines = [
        "<!-- Generated by scripts/generate_games_markdown.py. Do not edit manually. -->",
        "# 🎮 Supported games", "",
        "[← Project overview](README.md) · [Troubleshooting](TROUBLESHOOTING.md) · "
        "[Catalogue data](data/supported_games.json)", "",
        f"**Catalogue refreshed:** {updated}. Updated automatically by the daily GitHub refresh.", "",
        "| Games in catalogue | Adaptive triggers | Haptic feedback | Manual fix needed |",
        "| :---: | :---: | :---: | :---: |",
        f"| **{len(games)}** | **{adaptive}** | **{haptic}** | **{manual}** |", "",
        "Feature totals include both native support and manual fixes. This catalogue tracks "
        "DualSense support from PCGamingWiki; it does not certify every effect on every APEX model.", "",
        "**Legend:** ✅ Native support · 🛠️ Requires a manual fix · — Not listed for this feature.", "",
        "For 🛠️ games, apply the linked mod or configuration yourself before enabling automatic "
        "activation in ApexSenseBridge. Fix links are provided as references; ApexSenseBridge "
        "does not install or verify them. [About manual fixes](TROUBLESHOOTING.md#8-what-does-manual-fix-mean).", "",
    ]
    recent = sorted((game for game in games if added_date(game)),
                    key=lambda game: (-date.fromisoformat(added_date(game)).toordinal(), game["title"].casefold()))[:6]
    if recent:
        lines.extend(["## ✨ Most recent additions", "", "Dates show when a game entered the catalogue, not its release date.", "", "<table>"])
        for offset in range(0, len(recent), 3):
            lines.append("<tr>")
            for game in recent[offset:offset + 3]:
                title = html.escape(game["title"])
                url = html.escape(pcgw_url(game), quote=True)
                cover_url = safe_url(game.get("iconUrl", ""))
                cover = (f'<img src="{html.escape(cover_url, quote=True)}" width="100" height="150" '
                         f'alt="{html.escape(game["title"], quote=True)} cover"><br>') if cover_url else "🎮<br>"
                lines.append(f'<td align="center" width="230"><a href="{url}">{cover}<strong>{title}</strong></a>'
                             f'<br><sub>Added {added_date(game)}</sub></td>')
            lines.append("</tr>")
        lines.extend(["</table>", ""])
    groups = sorted({initial(game) for game in games}, key=lambda group: (group == "Other", group))
    lines.extend(["## 📚 Full catalogue", "", " · ".join(f"[{group}](#{group.lower()})" for group in groups), "",
                  "Use **Ctrl+F** (or **Cmd+F**) to find a game. Click its title to open PCGamingWiki.", ""])
    for group in groups:
        lines.extend([f"### {group}", "", "| Game | Adaptive triggers | Haptic feedback | Manual fix / instructions |",
                      "| :--- | :---: | :---: | :--- |"])
        for game in games:
            if initial(game) != group:
                continue
            title = f"[{cell(game['title'])}]({pcgw_url(game)})"
            app_id = game.get("steamAppId")
            if game.get("steamAppIdVerified") is True and isinstance(app_id, int) and app_id > 0:
                title += f" · [Steam](https://store.steampowered.com/app/{app_id}/)"
            lines.append(f"| {title} | {feature_status(game, 'adaptiveTriggers')} | "
                         f"{feature_status(game, 'hapticFeedback')} | {manual_links(game)} |")
        lines.append("")
    lines.extend(["---", "", "Generated from [data/supported_games.json](data/supported_games.json). "
                  "To regenerate locally: `python scripts/generate_games_markdown.py`. "
                  "Use `--check` to verify that this page matches the catalogue.", ""])
    return "\n".join(lines)


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--input", type=pathlib.Path, default=ROOT / "data" / "supported_games.json")
    parser.add_argument("--output", type=pathlib.Path, default=ROOT / "GAMES.md")
    parser.add_argument("--check", action="store_true", help="Fail if the generated page is missing or stale")
    args = parser.parse_args(argv)
    rendered = render_catalogue(json.loads(args.input.read_text(encoding="utf-8")))
    if args.check:
        if not args.output.exists() or args.output.read_text(encoding="utf-8") != rendered:
            print(f"Out of date: {args.output}. Run scripts/generate_games_markdown.py.")
            return 1
        print(f"Up to date: {args.output}")
        return 0
    args.output.write_text(rendered, encoding="utf-8", newline="\n")
    print(f"Generated {args.output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
